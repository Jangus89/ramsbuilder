// Universal keywords that boost relevance for any task
const UNIVERSAL_KEYWORDS = ['construction', 'risk assessment', 'coshh', 'riddor', 'ppe', 'first aid', 'hsg150', 'hsg65', 'hsg159'];

/**
 * Returns the most relevant HSE guidance entries for a given task.
 * @param {string} taskType
 * @param {number} limit
 * @returns {{ title: string, url: string }[]}
 */
export function filterGuidanceForTask(taskType, limit = 12) {
  const taskKws = TASK_KEYWORDS[taskType] || [];
  const allKws  = [...taskKws, ...UNIVERSAL_KEYWORDS];

  const scored = HSE_GUIDANCE.map(entry => {
    const text = entry.title.toLowerCase();
    let score = 0;
    for (const kw of taskKws)       { if (text.includes(kw.toLowerCase())) score += 3; }
    for (const kw of UNIVERSAL_KEYWORDS) { if (text.includes(kw.toLowerCase())) score += 1; }
    return { ...entry, score };
  });

  return scored
    .filter(e => e.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(({ title, url }) => ({ title, url }));
}

/**
 * Looks up a guidance entry by title fragment (for matching GPT-returned references back to URLs).
 */
export function findGuidanceUrl(titleFragment) {
  const frag = titleFragment.toLowerCase();
  const match = HSE_GUIDANCE.find(e => e.title.toLowerCase().includes(frag) || frag.includes(e.title.toLowerCase().slice(0, 20)));
  return match?.url || null;
}
